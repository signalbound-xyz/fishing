const base = (over: Partial<Scenario>): Scenario => ({ rules: 'chain', player: 'average', reel: 'current', world: WORLD_NOW, pattern: PATTERNS.daily, start: 'new', days: DAYS_NEW, ...over });
const runCache = new Map<string, CareerResult[]>();
/** Careers of a scenario, cached: several tables read the same runs. */
function run(over: Partial<Scenario>): CareerResult[] {
  const sc = base(over);
  const key = [sc.rules, sc.player, sc.reel, sc.world.name, sc.pattern.name, sc.start, sc.days, sc.goal ?? 'pearl', sc.buyLocations ? 'buy' : ''].join('|');
  let rs = runCache.get(key);
  if (!rs) runCache.set(key, (rs = careers(sc, RUNS, 11 + runCache.size)));
  return rs;
}
const veteran = (over: Partial<Scenario>): CareerResult[] => run({ start: 'veteran', days: DAYS_VETERAN, ...over });

const dayCell = (rs: CareerResult[], key: string): string => {
  const m = milestone(rs, key);
  return m.day === null ? (m.reached ? `in ${m.reached}/${rs.length} runs` : 'not in a year') : `day ${Math.round(m.day)}`;
};
/** Median over runs of a per-day rate. */
const perDay = (rs: CareerResult[], f: (r: CareerResult) => number, days: number): number => median(rs.map((r) => f(r) / days));
const upkeepOf = (r: CareerResult): number => r.spent.lures + r.spent.repairs;
const minutesOf = (r: CareerResult): number => r.sittings.reduce((a, s) => a + s.seconds, 0) / 60;
const sittingCasts = (rs: CareerResult[]): number => mean(rs.flatMap((r) => r.sittings.map((s) => s.casts)));
const sittingMinutes = (rs: CareerResult[]): number => mean(rs.flatMap((r) => r.sittings.map((s) => s.seconds / 60)));
const weekly = (rs: CareerResult[]): number => median(rs.flatMap((r) => r.weeks));

