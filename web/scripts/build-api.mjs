#!/usr/bin/env node
// Bundles the server code into one file per Vercel Function:
//   src/server/entry.ts        → api/daily-reward.js   the reward verifier, behind /api/daily-reward
//   src/server/keeperEntry.ts  → api/keeper.js         the operator's keeper, behind /api/keeper
// One file each because a function on Vercel is not bundled for us: its relative imports of the game's modules
// (no file extensions, `import.meta.env`) would not resolve there. npm dependencies (viem) stay imports and are
// installed by the host from package.json.
//
//   node scripts/build-api.mjs            writes the bundles
//   node scripts/build-api.mjs --check    exits 1 when a committed bundle differs from what the source builds to
//
// The bundles are built without any VITE_* variable: the functions take their network and addresses from their own
// environment at run time (web/DAILY_REWARDS.md, web/KEEPER.md), never from the page's build.
import { readFileSync, writeFileSync, existsSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { build } from 'vite';

const web = join(dirname(fileURLToPath(import.meta.url)), '..');
const FUNCTIONS = [
  { entry: 'src/server/entry.ts', file: 'daily-reward.js' },
  { entry: 'src/server/keeperEntry.ts', file: 'keeper.js' },
];

export async function bundle({ entry, file }) {
  const out = await build({
    root: web,
    configFile: false,
    envFile: false,
    logLevel: 'error',
    define: { 'import.meta.env.VITE_CHAIN_ID': 'undefined', 'import.meta.env.VITE_RPC_URL': 'undefined', 'import.meta.env.VITE_GAME_MODE': 'undefined' },
    build: {
      ssr: entry,
      write: false,
      minify: false,
      target: 'node20',
      rollupOptions: { output: { format: 'esm', entryFileNames: file, codeSplitting: false } },
    },
  });
  const chunks = (Array.isArray(out) ? out : [out]).flatMap((o) => o.output).filter((c) => c.type === 'chunk');
  if (chunks.length !== 1) throw new Error(`expected one chunk, got ${chunks.length}`);
  const banner = `// GENERATED by scripts/build-api.mjs from ${entry}. Do not edit: run \`pnpm build:api\`.\n`;
  return banner + chunks[0].code;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  let stale = false;
  for (const fn of FUNCTIONS) {
    const target = join(web, 'api', fn.file);
    const code = await bundle(fn);
    if (process.argv.includes('--check')) {
      const have = existsSync(target) ? readFileSync(target, 'utf8') : '';
      if (have !== code) {
        console.error(`[api] api/${fn.file} is not what src/server builds to: run \`pnpm build:api\` and commit it`);
        stale = true;
      } else console.log(`[api] api/${fn.file} is up to date`);
    } else {
      mkdirSync(dirname(target), { recursive: true });
      writeFileSync(target, code);
      console.log(`[api] wrote api/${fn.file} (${(code.length / 1024).toFixed(1)} kB)`);
    }
  }
  if (stale) process.exit(1);
}
