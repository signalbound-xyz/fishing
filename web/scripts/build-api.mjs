#!/usr/bin/env node
// Bundles the reward verifier (src/server/entry.ts) into one file, api/daily-reward.js: the Vercel Function behind
// /api/daily-reward. One file because a function on Vercel is not bundled for us: its relative imports of the
// game's modules (no file extensions, `import.meta.env`) would not resolve there. npm dependencies (viem) stay
// imports and are installed by the host from package.json.
//
//   node scripts/build-api.mjs            writes api/daily-reward.js
//   node scripts/build-api.mjs --check    exits 1 when the committed file differs from what the source builds to
//
// The bundle is built without any VITE_* variable: the verifier takes its network and addresses from its own
// environment at run time (web/DAILY_REWARDS.md), never from the page's build.
import { readFileSync, writeFileSync, existsSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { build } from 'vite';

const web = join(dirname(fileURLToPath(import.meta.url)), '..');
const target = join(web, 'api', 'daily-reward.js');

export async function bundle() {
  const out = await build({
    root: web,
    configFile: false,
    envFile: false,
    logLevel: 'error',
    define: { 'import.meta.env.VITE_CHAIN_ID': 'undefined', 'import.meta.env.VITE_RPC_URL': 'undefined', 'import.meta.env.VITE_GAME_MODE': 'undefined' },
    build: {
      ssr: 'src/server/entry.ts',
      write: false,
      minify: false,
      target: 'node20',
      rollupOptions: { output: { format: 'esm', entryFileNames: 'daily-reward.js', codeSplitting: false } },
    },
  });
  const chunks = (Array.isArray(out) ? out : [out]).flatMap((o) => o.output).filter((c) => c.type === 'chunk');
  if (chunks.length !== 1) throw new Error(`expected one chunk, got ${chunks.length}`);
  const banner = '// GENERATED by scripts/build-api.mjs from src/server/entry.ts. Do not edit: run `pnpm build:api`.\n';
  return banner + chunks[0].code;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const code = await bundle();
  if (process.argv.includes('--check')) {
    const have = existsSync(target) ? readFileSync(target, 'utf8') : '';
    if (have !== code) {
      console.error('[api] api/daily-reward.js is not what src/server builds to: run `pnpm build:api` and commit it');
      process.exit(1);
    }
    console.log('[api] api/daily-reward.js is up to date');
  } else {
    mkdirSync(dirname(target), { recursive: true });
    writeFileSync(target, code);
    console.log(`[api] wrote api/daily-reward.js (${(code.length / 1024).toFixed(1)} kB)`);
  }
}
